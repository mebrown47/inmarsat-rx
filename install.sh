# install.sh — install, update or remove inmarsat-observatory on this machine:
# the inmarsat-rx receiver (live page on :8892) and the Inmarsat Observatory
# dashboard (:8893), as systemd services that start at boot.
#
# Usage (from the repo checkout, as your normal user — it sudo's as needed):
#     ./install.sh                 first install (asks a few questions)
#     ./install.sh --update        git pull, rebuild, test, reinstall, restart
#     ./install.sh --reconfigure   ask the questions again, then reinstall
#     ./install.sh --uninstall     remove services and program files
#
# Options:
#     --yes          don't ask; take the defaults (or the existing config)
#     --no-deps      skip installing packages (you've done it yourself)
#     --dry-run      print what would be done as root, change nothing
#     -h, --help     show this help
#
# Where things go:
#     /opt/inmarsat-observatory/        program files (binary, observatory)
#     /etc/inmarsat-observatory.conf    your settings — edit this, not the units
#     /var/lib/inmarsat-observatory/    archive/ (JSONL) and observatory.db
#
# Re-running is safe. Settings, archive and database survive updates and
# uninstall. Adapted from vdl2-observatory's installer.
#
set -euo pipefail

# ---- pretty output ----------------------------------------------------------
if [ -t 1 ]; then B=$'\e[1m'; G=$'\e[32m'; Y=$'\e[33m'; R=$'\e[31m'; Z=$'\e[0m'; else B=; G=; Y=; R=; Z=; fi
say()  { printf '%s\n' "$*"; }
info() { printf '\n%s==>%s %s\n' "$B" "$Z" "$*"; }
ok()   { printf '  %sok%s   %s\n' "$G" "$Z" "$*"; }
warn() { printf '  %swarn%s %s\n' "$Y" "$Z" "$*"; }
die()  { printf '  %serror%s %s\n' "$R" "$Z" "$*" >&2; exit 1; }

# ---- fixed locations --------------------------------------------------------
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="$REPO_ROOT/build-install"
PREFIX=/opt/inmarsat-observatory
CONF=/etc/inmarsat-observatory.conf
DATA_DIR=/var/lib/inmarsat-observatory
ARCHIVE_DIR="$DATA_DIR/archive"
DB_PATH="$DATA_DIR/observatory.db"
UNIT_DIR=/etc/systemd/system
RX_UNIT="$UNIT_DIR/inmarsat-rx.service"
OBS_UNIT="$UNIT_DIR/inmarsat-observatory.service"
ROLLUP_UNIT="$UNIT_DIR/inmarsat-rollup.service"
ROLLUP_TIMER="$UNIT_DIR/inmarsat-rollup.timer"
MARKER="# Generated by inmarsat-observatory install.sh"
LIBACARS_TAG=v2.2.1

# ---- args -------------------------------------------------------------------
MODE=install; ASSUME_YES=0; DEPS=1; DRY_RUN=0; PULLED=0
ORIG_ARGS=("$@")
while [ $# -gt 0 ]; do
  case "$1" in
    --update)      MODE=update;;
    --reconfigure) MODE=reconfigure;;
    --uninstall)   MODE=uninstall;;
    --yes|-y)      ASSUME_YES=1;;
    --no-deps)     DEPS=0;;
    --dry-run)     DRY_RUN=1;;
    --pulled)      PULLED=1;;   # internal: --update re-running the new script
    -h|--help)     sed -n '2,27p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0;;
    *) die "unknown option: $1 (try --help)";;
  esac
  shift
done

# ---- helpers ----------------------------------------------------------------
# Everything that changes the system outside the checkout goes through as_root,
# so --dry-run can show it without doing it.
as_root() {
  if [ "$DRY_RUN" -eq 1 ]; then printf '  %s[dry-run]%s %s\n' "$Y" "$Z" "$*"; return 0; fi
  sudo "$@"
}
root_write() {
  local dst="$1" mode="$2" tmp
  tmp="$(mktemp)"; cat > "$tmp"
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '  %s[dry-run]%s write %s:\n' "$Y" "$Z" "$dst"; sed 's/^/      | /' "$tmp"
  else
    sudo install -m "$mode" "$tmp" "$dst"
  fi
  rm -f "$tmp"
}
ask() {
  local q="$1" def="$2" ans
  if [ "$ASSUME_YES" -eq 1 ] || [ ! -r /dev/tty ]; then printf '%s' "$def"; return; fi
  printf '  %s [%s]: ' "$q" "$def" > /dev/tty
  read -r ans < /dev/tty || ans=""
  printf '%s' "${ans:-$def}"
}
yes_no() { case "$(ask "$1 (y/n)" "$2")" in [Yy]*) return 0;; *) return 1;; esac; }
have() { command -v "$1" >/dev/null 2>&1; }

# ---- preflight --------------------------------------------------------------
info "Preflight"
[ "$(uname -s)" = Linux ] || die "Linux only"
[ "$(id -u)" -ne 0 ] || die "run as your normal user, not root — it uses sudo when it needs to"
have systemctl || die "systemd is required"
have sudo || die "sudo is required"
if [ "$DRY_RUN" -eq 0 ]; then sudo -v || die "sudo failed"; fi
RUN_USER="$(id -un)"
ok "user: $RUN_USER   arch: $(uname -m)   $(. /etc/os-release 2>/dev/null; echo "${PRETTY_NAME:-unknown OS}")"

# ---- uninstall --------------------------------------------------------------
if [ "$MODE" = uninstall ]; then
  info "Removing services and program files"
  as_root systemctl disable --now inmarsat-rx.service inmarsat-observatory.service inmarsat-rollup.timer 2>/dev/null || true
  as_root rm -f "$RX_UNIT" "$OBS_UNIT" "$ROLLUP_UNIT" "$ROLLUP_TIMER" /usr/local/bin/inmarsat-rx
  as_root rm -rf "$PREFIX"
  as_root systemctl daemon-reload
  ok "removed. Kept: $CONF and $DATA_DIR (delete by hand for a clean slate)"
  exit 0
fi

# ---- update: pull first, so everything below builds the new source ----------
if [ "$MODE" = update ] && [ "$PULLED" -eq 0 ]; then
  [ -f "$CONF" ] || die "no $CONF — run ./install.sh first"
  info "Updating the checkout"
  have git || die "git not found"
  git -C "$REPO_ROOT" pull --ff-only \
    || die "git pull failed (local changes or a diverged branch?) — fix the checkout and re-run"
  ok "now at $(git -C "$REPO_ROOT" describe --always --dirty --tags)"
  exec "$REPO_ROOT/install.sh" "${ORIG_ARGS[@]}" --pulled
fi

# ---- packages ---------------------------------------------------------------
install_libacars_from_source() {
  info "Building libacars $LIBACARS_TAG from source (no distro package)"
  local src; src="$(mktemp -d)"
  git clone -q --depth 1 --branch "$LIBACARS_TAG" https://github.com/szpajder/libacars "$src/libacars" \
    || die "could not clone libacars"
  cmake -S "$src/libacars" -B "$src/libacars/build" -DCMAKE_BUILD_TYPE=Release >/dev/null \
    && cmake --build "$src/libacars/build" -j"$(nproc)" >/dev/null \
    || die "libacars build failed"
  as_root cmake --install "$src/libacars/build" >/dev/null
  as_root ldconfig
  rm -rf "$src"
  ok "libacars $LIBACARS_TAG installed to /usr/local"
}

if [ "$DEPS" -eq 1 ]; then
  info "Packages"
  if have apt-get; then
    CORE=(build-essential cmake pkg-config git python3 curl usbutils libusb-1.0-0-dev
          libairspy-dev libhackrf-dev zlib1g-dev libxml2-dev)
    as_root apt-get install -y -q --no-install-recommends "${CORE[@]}" \
      || die "could not install the build tools — see apt's message above"
    ok "build tools, Airspy and HackRF support installed"
    if pkg-config --exists libacars-2 2>/dev/null; then
      ok "libacars $(pkg-config --modversion libacars-2) already present"
    elif apt-cache show libacars-dev >/dev/null 2>&1; then
      as_root apt-get install -y -q libacars-dev
    else
      install_libacars_from_source
    fi
  else
    warn "not a Debian/Ubuntu system — install by hand: cmake, a C compiler, libairspy, libhackrf,"
    warn "libacars-2, python3 (see README), then re-run with --no-deps"
  fi
fi

# ---- build + test -----------------------------------------------------------
info "Building"
mkdir -p "$BUILD_DIR"
cmake -S "$REPO_ROOT" -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release -DNATIVE=OFF > "$BUILD_DIR.log" 2>&1 \
  && cmake --build "$BUILD_DIR" -j"$(nproc)" >> "$BUILD_DIR.log" 2>&1 \
  || { tail -20 "$BUILD_DIR.log"; die "build failed — full log: $BUILD_DIR.log"; }
BIN="$BUILD_DIR/inmarsat-rx"
ok "built $BIN"
grep -q 'libacars-2 found' "$BUILD_DIR.log" && ok "libacars enabled (CPDLC, ADS-C)" \
  || warn "built WITHOUT libacars — ACARS text only, no CPDLC/ADS-C decoding"
grep -q 'libAIRSPY found' "$BUILD_DIR.log" || warn "built without libairspy: no Airspy input"
grep -q 'libHACKRF found' "$BUILD_DIR.log" || warn "built without libhackrf: no HackRF input"

info "Testing"
"$REPO_ROOT/tests/run_tests.sh" "$BUILD_DIR" > "$BUILD_DIR/tests.log" 2>&1 \
  || { tail -20 "$BUILD_DIR/tests.log"; die "tests failed — not installing. Log: $BUILD_DIR/tests.log"; }
ok "$(grep '^RESULT' "$BUILD_DIR/tests.log")"

# ---- device access ----------------------------------------------------------
# The service runs headless with SupplementaryGroups=plugdev, so the SDR's USB node must be
# group-writable by plugdev. The kernel's V4L2 airspy driver grabs an R2 on plug-in (it becomes
# a radio device and libairspy can't claim it), so it is blacklisted.
info "Device access"
SDR_RULE=/etc/udev/rules.d/52-inmarsat-observatory.rules
if getent group plugdev >/dev/null 2>&1; then
  root_write "$SDR_RULE" 0644 <<'RULE'
# Written by inmarsat-observatory install.sh: let the plugdev group (the inmarsat-rx
# service's) open an Airspy R2/Mini or a HackRF, logged in at the screen or not.
SUBSYSTEM=="usb", ATTR{idVendor}=="1d50", ATTR{idProduct}=="60a1", MODE="0660", GROUP="plugdev"
SUBSYSTEM=="usb", ATTR{idVendor}=="1d50", ATTR{idProduct}=="6089", MODE="0660", GROUP="plugdev"
SUBSYSTEM=="usb", ATTR{idVendor}=="1d50", ATTR{idProduct}=="cc15", MODE="0660", GROUP="plugdev"
RULE
  as_root udevadm control --reload-rules
  as_root udevadm trigger --subsystem-match=usb --attr-match=idVendor=1d50
  ok "udev rule: plugdev can open an Airspy or HackRF ($SDR_RULE)"
  if [[ " $(id -nG "$RUN_USER") " != *" plugdev "* ]]; then
    as_root usermod -aG plugdev "$RUN_USER"
    warn "added $RUN_USER to plugdev: log out and back in to use the SDR from your own shell"
  fi
else
  warn "no plugdev group on this system: the service may not be able to open the SDR"
fi
BLACKLIST=/etc/modprobe.d/blacklist-airspy-v4l2.conf
if [ ! -f "$BLACKLIST" ]; then
  printf '# Written by inmarsat-observatory install.sh: libairspy, not the V4L2 driver, runs the R2.\nblacklist airspy\n' \
    | root_write "$BLACKLIST" 0644
  ok "kernel airspy (V4L2) driver blacklisted"
fi
if lsmod 2>/dev/null | grep -q '^airspy '; then as_root modprobe -r airspy || true; fi

# ---- current settings -------------------------------------------------------
# The parts of RX_ARGS the questions cover, so --reconfigure offers them as the defaults and
# changing one doesn't reset the rest; CUR_KEEP holds everything else, carried over as it is.
parse_current() {
  local -a w; read -r -a w <<<"$1"
  CUR_SRC=airspy; CUR_PLAN=i4f3; CUR_GAIN=""; CUR_BIAS=n; CUR_SCAN=y; CUR_UDP=""; CUR_STATION=""; CUR_KEEP=""
  CUR_CENTER=""
  local i=0 k v n=${#w[@]}
  while [ "$i" -lt "$n" ]; do
    k="${w[$i]}"; v=""; i=$((i+1))
    case "$k" in --*=*) v="${k#*=}"; k="${k%%=*}";; esac
    next() { if [ -z "$v" ] && [ "$i" -lt "$n" ]; then v="${w[$i]}"; i=$((i+1)); fi; }
    case "$k" in
      -i|--input)    next; CUR_SRC="$v";;
      --plan)        next; CUR_PLAN="$v";;
      -g|--gain)     next; CUR_GAIN="$v";;
      -b|--bias-tee) CUR_BIAS=y;;
      --scan)        CUR_SCAN=y;;
      -u|--udp)      next; CUR_UDP+=" $v";;
      --station)     next; CUR_STATION="$v";;
      -F|--center)   next; CUR_CENTER="$v";;
      -q|--quiet)    ;;
      *)
        CUR_KEEP+=" ${w[$((i-1))]}"
        while [ "$i" -lt "$n" ] && [[ "${w[$i]}" != -* ]]; do CUR_KEEP+=" ${w[$i]}"; i=$((i+1)); done;;
    esac
  done
  [[ " $1 " == *" --scan "* ]] || { [ -n "$1" ] && CUR_SCAN=n; }
  CUR_UDP="$(echo $CUR_UDP)"; CUR_KEEP="$(echo $CUR_KEEP)"
}

# ---- config -----------------------------------------------------------------
if [ -f "$CONF" ] && [ "$MODE" != reconfigure ]; then
  info "Config"
  ok "keeping $CONF (./install.sh --reconfigure to redo it)"
  # shellcheck disable=SC1090
  . "$CONF"
else
  info "Config"
  WEB_PORT=8892; OBS_PORT=8893; RX_ARGS=""
  # shellcheck disable=SC1090
  [ -f "$CONF" ] && . "$CONF"
  parse_current "$RX_ARGS"
  [ -n "$RX_ARGS" ] && say "  Current settings are the defaults: press Enter to keep each one."
  say "  Sources: airspy (R2/Mini on USB), hackrf, rtl_tcp:HOST:PORT, spyserver:HOST:PORT"
  src="$(ask "Source" "$CUR_SRC")"
  say "  Plans: $("$BIN" --plans | awk '{printf "%s%s", sep, $1; sep=", "}')  (comma-separated, or all)"
  plan="$(ask "Satellite plans" "$CUR_PLAN")"
  case "$src" in
    airspy*) gain="$(ask "Linearity gain 0-21" "${CUR_GAIN:-12}")";;
    hackrf*) gain="$(ask "HackRF LNA,VGA in dB" "${CUR_GAIN:-32,20}")";;
    rtl_tcp*) gain="$(ask "Gain in dB, or auto" "${CUR_GAIN:-auto}")";;
    *) gain="$(ask "Node gain index, or default" "${CUR_GAIN:-default}")";;
  esac
  RX_ARGS="-i $src --plan $plan"
  case "$gain" in auto|default|"") ;; *) RX_ARGS+=" -g $gain";; esac
  case "$src" in airspy*|hackrf*|rtl_tcp*)
    yes_no "Power the antenna's LNA through the coax (bias-tee)" "$CUR_BIAS" && RX_ARGS+=" -b";;
  esac
  yes_no "Scan the band for carriers the plans don't list" "$CUR_SCAN" && RX_ARGS+=" --scan"
  if [ -n "$CUR_CENTER" ]; then RX_ARGS+=" -F $CUR_CENTER"; fi
  feeds="$(ask "Feed records over UDP: HOST:PORT destinations, space-separated (none for none)" "${CUR_UDP:-none}")"
  if [ "$feeds" != none ]; then for f in $feeds; do RX_ARGS+=" -u $f"; done; fi
  st="$(ask "Station name for the records and the live page, one word (none for none)" "${CUR_STATION:-none}")"
  [ "$st" != none ] && RX_ARGS+=" --station $st"
  [ -n "$CUR_KEEP" ] && { RX_ARGS+=" $CUR_KEEP"; ok "kept as they were (edit $CONF to change them): $CUR_KEEP"; }
  RX_ARGS="$(echo "$RX_ARGS" | sed 's/^ *//; s/  */ /g; s/ *$//')"
  root_write "$CONF" 0644 <<EOF
# inmarsat-observatory settings — written by install.sh, yours to edit.
# After changing anything:   sudo systemctl restart inmarsat-rx
# Ports or user changed?     re-run ./install.sh so the services follow.
# All options:               inmarsat-rx --help      Plans: inmarsat-rx --plans
#
# Archive and database always live in $DATA_DIR

# Who the services run as.
RUN_USER="$RUN_USER"

# Receiver flags (source, plans, gain, feeds). --web, --archive and -q are added for you.
RX_ARGS="$RX_ARGS"

# Live page port, and Observatory dashboard port.
WEB_PORT="$WEB_PORT"
OBS_PORT="$OBS_PORT"
EOF
  ok "wrote $CONF"
fi
: "${WEB_PORT:=8892}" "${OBS_PORT:=8893}" "${RUN_USER:=$(id -un)}"

# One SDR serves one program: say so if another receiver holds it.
case " $RX_ARGS " in
  *" -i airspy"*|*" --input airspy"*)
    for other in iridium-sniffer airspy-spyserver spyserver; do
      if systemctl is-active --quiet "$other" 2>/dev/null; then
        warn "$other is running and may hold the Airspy — inmarsat-rx needs its own SDR (or stop $other)"
      fi
    done;;
esac

# ---- install files ----------------------------------------------------------
info "Installing program files to $PREFIX"
STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/bin" "$STAGE/observatory"
cp "$BIN" "$STAGE/bin/"
cp "$REPO_ROOT"/observatory/*.py "$STAGE/observatory/"
git -C "$REPO_ROOT" describe --always --dirty --tags > "$STAGE/VERSION" 2>/dev/null || echo unknown > "$STAGE/VERSION"
# Swap the whole tree in by rename, so the services never see half a copy.
as_root rm -rf "$PREFIX.new" "$PREFIX.old"
as_root cp -r "$STAGE" "$PREFIX.new"
as_root chmod -R a+rX "$PREFIX.new"
if [ "$DRY_RUN" -eq 1 ] || [ -d "$PREFIX" ]; then as_root mv "$PREFIX" "$PREFIX.old"; fi
as_root mv "$PREFIX.new" "$PREFIX"
as_root rm -rf "$PREFIX.old"
as_root ln -sf "$PREFIX/bin/inmarsat-rx" /usr/local/bin/inmarsat-rx
ok "version $(cat "$STAGE/VERSION")"
as_root mkdir -p "$ARCHIVE_DIR"
as_root chown -R "$RUN_USER:" "$DATA_DIR"
ok "data in $DATA_DIR"

# ---- services ---------------------------------------------------------------
info "Services"
for u in "$RX_UNIT" "$OBS_UNIT" "$ROLLUP_UNIT" "$ROLLUP_TIMER"; do
  if [ -f "$u" ] && ! head -1 "$u" | grep -qF "$MARKER"; then
    BAKU="$DATA_DIR/$(basename "$u").$(date +%Y%m%d-%H%M%S)"
    as_root cp "$u" "$BAKU"
    warn "replacing a hand-written $u (saved a copy as $BAKU)"
  fi
done
GROUPS_LINE=""
getent group plugdev >/dev/null 2>&1 && GROUPS_LINE="SupplementaryGroups=plugdev"
PY="$(command -v python3)"
root_write "$RX_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=inmarsat-observatory receiver (inmarsat-rx, live page on :$WEB_PORT)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$RUN_USER
$GROUPS_LINE
EnvironmentFile=$CONF
WorkingDirectory=$DATA_DIR
ExecStart=$PREFIX/bin/inmarsat-rx \$RX_ARGS -q --web \${WEB_PORT} --observatory-port \${OBS_PORT} --archive $ARCHIVE_DIR --stats 600
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
root_write "$OBS_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=Inmarsat Observatory dashboard on :$OBS_PORT
After=network.target

[Service]
Type=simple
User=$RUN_USER
EnvironmentFile=$CONF
ExecStart=$PY $PREFIX/observatory/server.py --db $DB_PATH --port \${OBS_PORT} --live-port \${WEB_PORT} --host 0.0.0.0
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
root_write "$ROLLUP_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=Inmarsat Observatory: fold the archive into the database

[Service]
Type=oneshot
User=$RUN_USER
Nice=10
ExecStart=$PY $PREFIX/observatory/rollup.py --archive $ARCHIVE_DIR --db $DB_PATH
EOF
root_write "$ROLLUP_TIMER" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=Inmarsat Observatory rollup every minute

[Timer]
OnBootSec=1min
OnUnitActiveSec=1min

[Install]
WantedBy=timers.target
EOF
as_root systemctl daemon-reload
as_root systemctl enable inmarsat-rx.service inmarsat-observatory.service inmarsat-rollup.timer
as_root systemctl restart inmarsat-rx.service
ok "inmarsat-rx enabled and (re)started"
if [ "$DRY_RUN" -eq 1 ]; then
  printf '  %s[dry-run]%s first rollup\n' "$Y" "$Z"
elif ls "$ARCHIVE_DIR"/inmarsat-*.jsonl >/dev/null 2>&1 \
     && sudo -u "$RUN_USER" "$PY" "$PREFIX/observatory/rollup.py" --archive "$ARCHIVE_DIR" --db "$DB_PATH" \
        > "$BUILD_DIR/rollup.log" 2>&1; then
  ok "first rollup done"
else
  ok "the rollup timer will build the database once the receiver has archived something"
fi
as_root systemctl restart inmarsat-observatory.service inmarsat-rollup.timer
ok "Observatory and rollup timer enabled and (re)started"

# ---- health -----------------------------------------------------------------
info "Checking"
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"; IP="${IP:-localhost}"
if [ "$DRY_RUN" -eq 1 ]; then
  ok "dry run — nothing was changed"
else
  up=0
  for _ in $(seq 1 20); do
    if curl -fs -o /dev/null "http://127.0.0.1:$WEB_PORT/healthz"; then up=1; break; fi
    sleep 1
  done
  if [ "$up" -eq 1 ]; then ok "live page answering on :$WEB_PORT"
  else
    warn "live page not answering on :$WEB_PORT yet — recent log:"
    journalctl -u inmarsat-rx -n 15 --no-pager 2>/dev/null | sed 's/^/      /' || true
  fi
  up=0
  for _ in $(seq 1 10); do
    if curl -fs -o /dev/null "http://127.0.0.1:$OBS_PORT/healthz"; then up=1; break; fi
    sleep 1
  done
  [ "$up" -eq 1 ] && ok "Observatory answering on :$OBS_PORT" \
    || warn "Observatory not answering on :$OBS_PORT — journalctl -u inmarsat-observatory"
fi

info "Done"
say "  Live page:    ${B}http://$IP:$WEB_PORT/${Z}"
say "  Observatory:  ${B}http://$IP:$OBS_PORT/${Z}   (fills in as the rollup runs, every minute)"
say "  Settings:     $CONF  then  sudo systemctl restart inmarsat-rx"
say "  Logs:         journalctl -u inmarsat-rx -f"
say "  Update:       ./install.sh --update"
if have ufw && [ "$DRY_RUN" -eq 0 ] && sudo ufw status 2>/dev/null | grep -q '^Status: active'; then
  warn "ufw is active — for LAN access:  sudo ufw allow $WEB_PORT/tcp && sudo ufw allow $OBS_PORT/tcp"
fi
